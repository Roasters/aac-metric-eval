"""
Compute the 13 base metrics on the AudioCaps core sets (originals + masking + synonym
+ swap) generated by audiocaps/audiocaps_perturb.py, so they can be paired with CAF.

Reads RESULTS_DIR/audiocaps/<name>_candidates.json, runs evaluate_aac_batch, writes
RESULTS_DIR/audiocaps/<name>_scores.json (same schema as the Clotho *_scores files).

    CUDA_VISIBLE_DEVICES=<gpu> python audiocaps/eval_audiocaps_base.py
"""

import os
import sys
import json
import argparse

import torch

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from evaluate import evaluate_aac_batch  # noqa: E402

RESULTS_DIR = os.environ.get("CAF_RESULTS_DIR",
                             os.environ.get("RESULTS_DIR", os.path.join(REPO, "results")))
AC_DIR = os.path.join(RESULTS_DIR, "audiocaps")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sets", nargs="*",
                    default=["original", "masked", "synonym", "swap_adjacent"])
    ap.add_argument("--batch_size", type=int, default=1024)
    args = ap.parse_args()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    for name in args.sets:
        cpath = os.path.join(AC_DIR, f"{name}_candidates.json")
        spath = os.path.join(AC_DIR, f"{name}_scores.json")
        if not os.path.exists(cpath):
            print(f"[skip] {name}: {cpath} missing"); continue
        if os.path.exists(spath):
            print(f"[cached] {name}: {spath} exists"); continue
        d = json.load(open(cpath))
        cands, refs, aps = d["candidates"], d["references"], d["audio_paths"]
        print(f"=== {name}: {len(cands)} candidates ===", flush=True)
        scores = evaluate_aac_batch(cands, refs, batch_size=args.batch_size,
                                    device=device, audio_paths=aps, ignore_all=True)
        with open(spath, "w") as f:
            json.dump(scores, f)
        print(f"  wrote {spath}", flush=True)


if __name__ == "__main__":
    main()
